param(
    [string]$Browser = "Chrome"
)

$ErrorActionPreference = "Stop"
$Root = Split-Path -Parent $PSScriptRoot
Set-Location $Root

$EvidenceDir = Join-Path $Root "docs/evidence/lab6"
$ArtifactsDir = Join-Path $Root "TestResults/lab6/artifacts"
New-Item -ItemType Directory -Force -Path $EvidenceDir | Out-Null
New-Item -ItemType Directory -Force -Path $ArtifactsDir | Out-Null

$env:TEST_BROWSER = $Browser
$env:TEST_ARTIFACTS = $ArtifactsDir
$env:DOTNET_ROLL_FORWARD = "Major"

Write-Host "=== 1. Build & static/unit checks ==="
$BuildLog = Join-Path $EvidenceDir "build.log"
dotnet build SauceDemo.Tests --no-restore *> $BuildLog
if ($LASTEXITCODE -ne 0) {
    dotnet build SauceDemo.Tests *> $BuildLog
    if ($LASTEXITCODE -ne 0) { throw "Build failed. See $BuildLog" }
}
dotnet run --project Checks/Lab5Checks.csproj --no-build *> (Join-Path $EvidenceDir "checks.log")
if ($LASTEXITCODE -ne 0) {
    dotnet run --project Checks/Lab5Checks.csproj *> (Join-Path $EvidenceDir "checks.log")
    if ($LASTEXITCODE -ne 0) { throw "Lab5/Lab6Checks failed." }
}

Write-Host "=== 2. Part A: Filter by [Category] ==="
dotnet test SauceDemo.Tests --no-build --filter "Category=Smoke" --logger "trx;LogFileName=smoke.trx" --results-directory $EvidenceDir *> (Join-Path $EvidenceDir "smoke.log")
if ($LASTEXITCODE -ne 0) { throw "Category=Smoke failed." }

dotnet test SauceDemo.Tests --no-build --filter "Category!=Slow" --logger "trx;LogFileName=not-slow.trx" --results-directory $EvidenceDir *> (Join-Path $EvidenceDir "not-slow.log")
if ($LASTEXITCODE -ne 0) { throw "Category!=Slow failed." }

Write-Host "=== 3. Part B: Logging PASS + intentional FAIL ([INFO] and [ERROR]) ==="
$LogPassFailPath = Join-Path $EvidenceDir "log-pass-fail.log"
$ReportsSubdir = Join-Path $ArtifactsDir "reports"
$FilterPartB = "FullyQualifiedName=SauceDemo.Tests.Tests.LoginTests.PageTitle|FullyQualifiedName=SauceDemo.Tests.Tests.LabTests.DynamicLoadingWithoutWait"
$FilterExplicitFail = "FullyQualifiedName=SauceDemo.Tests.Tests.LabTests.DynamicLoadingWithoutWait"
$ErrorActionPreference = "Continue"
dotnet test SauceDemo.Tests --no-build --filter $FilterPartB -l "console;verbosity=detailed" --logger "trx;LogFileName=log-pass-fail.trx" --results-directory $EvidenceDir *> $LogPassFailPath
if (-not ((Get-Content $LogPassFailPath -Raw) -match "\[ERROR\]")) {
    Add-Content -Path $LogPassFailPath -Value "`n--- Explicit failure run (DynamicLoadingWithoutWait) ---"
    dotnet test SauceDemo.Tests --no-build --filter $FilterExplicitFail -l "console;verbosity=detailed" --logger "trx;LogFileName=log-fail-explicit.trx" --results-directory $EvidenceDir *>> $LogPassFailPath
}
if (Test-Path $ReportsSubdir) {
    Get-ChildItem $ReportsSubdir -Filter "ketqua-baocao.*" | ForEach-Object {
        Copy-Item $_.FullName (Join-Path $EvidenceDir ($_.Name -replace '^ketqua-baocao', 'pass-fail-baocao')) -Force
    }
}
$ScreenshotsOutDir = Join-Path $EvidenceDir "screenshots"
New-Item -ItemType Directory -Force -Path $ScreenshotsOutDir | Out-Null
$failPng = Get-ChildItem $ArtifactsDir -Recurse -Filter "DynamicLoadingWithoutWait.png" -ErrorAction SilentlyContinue | Select-Object -First 1
if ($failPng) {
    Copy-Item $failPng.FullName (Join-Path $ScreenshotsOutDir "DynamicLoadingWithoutWait.png") -Force
}
$ErrorActionPreference = "Stop"

Write-Host "=== 4. Part C: TRX -> HTML (trxlog2html) & Excel/PDF/HTML reports ==="
if (Test-Path $ArtifactsDir) { Remove-Item $ArtifactsDir -Recurse -Force }
New-Item -ItemType Directory -Force -Path $ArtifactsDir | Out-Null
dotnet test SauceDemo.Tests --no-build --logger "trx;LogFileName=ketqua.trx" --results-directory $EvidenceDir *> (Join-Path $EvidenceDir "ketqua-console.log")
if ($LASTEXITCODE -ne 0) { throw "Full suite run for ketqua.trx failed." }
if (Test-Path $ReportsSubdir) {
    Copy-Item (Join-Path $ReportsSubdir "ketqua-baocao.*") $EvidenceDir -Force
}

$trx2html = Get-Command trxlog2html -ErrorAction SilentlyContinue
if (-not $trx2html) {
    Write-Host "Installing trxlog2html global tool..."
    $ErrorActionPreference = "Continue"
    dotnet tool install --global trxlog2html
    $ErrorActionPreference = "Stop"
    $trx2html = Get-Command trxlog2html -ErrorAction SilentlyContinue
}
if ($trx2html) {
    trxlog2html -i (Join-Path $EvidenceDir "ketqua.trx") -o (Join-Path $EvidenceDir "ketqua.html")
} else {
    Write-Warning "trxlog2html not available; ketqua-baocao.html was generated by TestReportCollector."
}

Write-Host "=== 5. Part D: Sequential vs Parallel timing comparison ==="
dotnet test SauceDemo.Tests --no-build --logger "trx;LogFileName=sequential.trx" --results-directory $EvidenceDir -- NUnit.NumberOfTestWorkers=0 *> (Join-Path $EvidenceDir "sequential.log")
if ($LASTEXITCODE -ne 0) { throw "Sequential run failed." }

dotnet test SauceDemo.Tests --no-build --logger "trx;LogFileName=parallel.trx" --results-directory $EvidenceDir *> (Join-Path $EvidenceDir "parallel.log")
if ($LASTEXITCODE -ne 0) { throw "Parallel run failed." }

function Read-TrxSummary([string]$TrxPath) {
    [xml]$doc = Get-Content $TrxPath -Raw
    $ns = New-Object System.Xml.XmlNamespaceManager($doc.NameTable)
    $ns.AddNamespace("t", "http://microsoft.com/schemas/VisualStudio/TeamTest/2010")
    $times = $doc.SelectSingleNode("//t:Times", $ns)
    $counters = $doc.SelectSingleNode("//t:Counters", $ns)
    $start = [DateTimeOffset]::Parse($times.start)
    $finish = [DateTimeOffset]::Parse($times.finish)
    return [PSCustomObject]@{
        File = [IO.Path]::GetFileName($TrxPath)
        Executed = [int]$counters.executed
        Passed = [int]$counters.passed
        Failed = [int]$counters.failed
        WallSeconds = [Math]::Round(($finish - $start).TotalSeconds, 2)
    }
}

$seqSummary = Read-TrxSummary (Join-Path $EvidenceDir "sequential.trx")
$parSummary = Read-TrxSummary (Join-Path $EvidenceDir "parallel.trx")
$seqSummary, $parSummary | Format-Table -AutoSize

Write-Host "=== 6. Run Lab 6 native verification ==="
dotnet run --project Checks/Lab5Checks.csproj --no-build -- --require-evidence
if ($LASTEXITCODE -ne 0) {
    dotnet run --project Checks/Lab5Checks.csproj -- --require-evidence
    if ($LASTEXITCODE -ne 0) { throw "Lab 6 evidence verification failed." }
}
